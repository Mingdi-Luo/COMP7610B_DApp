import assert from "node:assert/strict";
import { readFile, writeFile, mkdir, copyFile, readdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const read = async (file) => readFile(path.join(root, file), "utf8");
const dataset = JSON.parse(await read("palworld-dataset.json"));
const official = JSON.parse(await read("DT_PalMonsterParameter_Common.json"))[0].Rows;
const order = JSON.parse(await read("scripts/species-order.json"));
const check = process.argv.includes("--check");
assert.equal(dataset.pals.length, 136);
assert.deepEqual(dataset.pals.map((pal) => pal.codename), order, "speciesId order changed; explicit migration required");
assert.equal(new Set(order).size, 136);
assert.equal(new Set(dataset.pals.map((pal) => pal.slug)).size, 136);

// Preserve the existing enum IDs; official Ice/Earth and Dark/Dragon differ.
const elements = { None: 9, Normal: 0, Fire: 1, Water: 2, Leaf: 3, Electricity: 4, Earth: 5, Ice: 6, Dragon: 7, Dark: 8 };
const elementNames = ["Neutral", "Fire", "Water", "Grass", "Electric", "Ground", "Ice", "Dragon", "Dark", "None"];
const rarities = ["Common", "Rare", "Legendary"];
const species = dataset.pals.map((pal, speciesId) => {
  const source = official[pal.codename];
  assert.ok(source, `Missing official codename: ${pal.codename}`);
  for (const [field, original] of Object.entries({ hp: "Hp", shotAttack: "ShotAttack", defense: "Defense", rarity: "Rarity", combiRank: "CombiRank" })) {
    assert.equal(pal[field], source[original], `${pal.codename}.${field}`);
  }
  for (const index of [1, 2]) {
    assert.equal(pal[`element${index}`].id, Number(source[`ElementType${index}`].split("::")[1]));
    assert.equal(["None", "Normal", "Fire", "Water", "Leaf", "Electricity", "Ice", "Earth", "Dark", "Dragon"][pal[`element${index}`].id], pal[`element${index}`].name);
  }
  assert.match(pal.slug, /^[a-z0-9-]+$/);
  assert.equal(pal.image, `${dataset.meta.imageRoot}/${pal.slug}.png`);
  for (const stat of [pal.hp, pal.shotAttack, pal.defense, pal.combiRank]) assert.ok(Number.isInteger(stat) && stat > 0 && stat <= 65535);
  // Economic tiers only. Original pack odds/prices/merge/decompose rules stay intact.
  const rarity = pal.rarity <= 4 ? 0 : pal.rarity <= 9 ? 1 : 2;
  return {
    speciesId, codename: pal.codename, slug: pal.slug, name: pal.nameZh,
    nameEn: pal.nameEn, nameZh: pal.nameZh, paldexNo: pal.paldexNo,
    image: `/pals/${pal.slug}.png`, lore: `${pal.nameZh} · ${pal.nameEn}`,
    element: elements[pal.element1.name], secondElement: elements[pal.element2.name],
    rarity, basePower: [20, 50, 80][rarity], breedRank: pal.combiRank,
    maxHP: pal.hp, atk: pal.shotAttack, def: pal.defense,
  };
});
const byName = new Map(species.map((pal) => [pal.nameEn, pal.speciesId]));
const recipes = dataset.specialCombos.map(({ parents, child }) => {
  const ids = parents.map((parent) => byName.get(parent.nameEn));
  const childId = byName.get(child.nameEn);
  assert.ok([...ids, childId].every((id) => id !== undefined), `Unresolved recipe: ${child.nameEn}`);
  return { parents: ids, child: childId };
});
assert.equal(new Set(recipes.map(({ parents }) => [...parents].sort((a, b) => a - b).join(","))).size, recipes.length);

async function output(file, content) {
  if (check) assert.equal(await read(file), content, `${file} is stale; run node scripts/sync-palworld.mjs`);
  else await writeFile(path.join(root, file), content);
}

let cards = await read("contracts/contracts/ElementCards.sol");
const start = cards.indexOf("        // Species IDs follow this order.");
const end = cards.indexOf("\n    }", start);
assert.ok(start !== -1 && end > start);
const lines = ["        // Species IDs follow this order. Generated from palworld-dataset.json.",
  "        // Order locked by scripts/species-order.json; rarity and power are economic metadata only."];
for (const pal of species) {
  lines.push(`        _addSpecies(Element.${elementNames[pal.element]}, Element.${elementNames[pal.secondElement]}, Rarity.${rarities[pal.rarity]}, ${pal.basePower}, ${pal.breedRank}, ${pal.maxHP}, ${pal.atk}, ${pal.def}); // ${pal.speciesId}: ${pal.codename} -> ${pal.slug}`);
}
lines.push("", "        // Dataset special recipes; keep the existing rank-average fallback and lower-ID tie break.");
for (const recipe of recipes) lines.push(`        _recipes[_recipeKey(${recipe.parents.join(", ")})] = ${recipe.child + 1}; // ${species[recipe.child].codename}`);
cards = cards.slice(0, start) + lines.join("\n") + cards.slice(end);
await output("contracts/contracts/ElementCards.sol", cards);
await output("frontend/src/config/species.js",
  "// Generated by scripts/sync-palworld.mjs from palworld-dataset.json. Array index = speciesId.\n" +
  `export const SPECIES = ${JSON.stringify(species, null, 2)};\n\n` +
  `export const RECIPES = ${JSON.stringify(recipes, null, 2)};\n\n` +
  `export const ELEMENT_ICONS = ${JSON.stringify({ Neutral: "⚪", Fire: "🔥", Water: "💧", Grass: "🌿", Electric: "⚡", Ground: "⛰️", Ice: "❄️", Dragon: "🐲", Dark: "🌑", None: "" }, null, 2)};\n`);
const target = path.join(root, "frontend/public/pals");
if (!check) await mkdir(target, { recursive: true });
for (const pal of species) {
  const source = path.join(root, dataset.meta.imageRoot, `${pal.slug}.png`);
  const dest = path.join(target, `${pal.slug}.png`);
  if (!check) await copyFile(source, dest);
  assert.deepEqual(await readFile(dest), await readFile(source), `Image mismatch: ${pal.slug}`);
}
assert.deepEqual((await readdir(target)).sort(), species.map((pal) => `${pal.slug}.png`).sort());
console.log(`${check ? "Verified" : "Generated"} ${species.length} species, ${recipes.length} recipes and ${species.length} identical images.`);
